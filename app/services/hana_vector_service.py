import json
from typing import List, Dict, Any

from app.services.hana_connection import get_hana_connection


class HanaVectorService:
    """
    Handles vector storage and similarity search
    in SAP HANA Cloud.

    Embeddings are generated by EmbeddingService.

    Embedding model:
        SAP_NEB.20240715

    Vector dimension:
        768
    """

    DIMENSION = 768

    def __init__(self):
        self.connection = None

    def _get_connection(self):

        if self.connection is None:
            self.connection = get_hana_connection()

        return self.connection

    # ==================================================
    # INSERT CHUNK
    # ==================================================

    def insert_chunk(
        self,
        chunk_id: str,
        document_id: str,
        chunk_index: int,
        chunk_text: str,
        embedding: List[float],
    ) -> None:

        if not chunk_text or not chunk_text.strip():
            raise ValueError(
                "Chunk text cannot be empty."
            )

        if len(embedding) != self.DIMENSION:
            raise ValueError(
                f"Embedding must contain "
                f"{self.DIMENSION} values. "
                f"Received {len(embedding)}."
            )

        connection = self._get_connection()
        cursor = connection.cursor()

        sql = """
            INSERT INTO RAG_DOCUMENT_CHUNKS
            (
                ID,
                DOCUMENT_ID,
                CHUNK_INDEX,
                CHUNK_TEXT,
                EMBEDDING
            )
            VALUES (
                ?,
                ?,
                ?,
                ?,
                TO_REAL_VECTOR(?)
            )
        """

        try:

            vector_string = json.dumps(
                embedding
            )

            cursor.execute(
                sql,
                (
                    chunk_id,
                    document_id,
                    chunk_index,
                    chunk_text,
                    vector_string,
                ),
            )

            connection.commit()

        finally:
            cursor.close()

    # ==================================================
    # VECTOR SEARCH
    # ==================================================

    def search_similar_chunks(
        self,
        query_embedding: List[float],
        top_k: int = 5,
        document_id: str | None = None,
    ) -> List[Dict[str, Any]]:

        if len(query_embedding) != self.DIMENSION:
            raise ValueError(
                f"Query embedding must contain "
                f"{self.DIMENSION} values. "
                f"Received {len(query_embedding)}."
            )

        if top_k <= 0:
            raise ValueError(
                "top_k must be greater than 0."
            )

        connection = self._get_connection()
        cursor = connection.cursor()

        vector_string = json.dumps(
            query_embedding
        )

        # ---------------------------------------
        # Search within specific document
        # ---------------------------------------

        if document_id:

            sql = """
                SELECT TOP ?
                    ID,
                    DOCUMENT_ID,
                    CHUNK_INDEX,
                    CHUNK_TEXT,
                    COSINE_SIMILARITY(
                        EMBEDDING,
                        TO_REAL_VECTOR(?)
                    ) AS SCORE
                FROM RAG_DOCUMENT_CHUNKS
                WHERE DOCUMENT_ID = ?
                ORDER BY SCORE DESC
            """

            parameters = (
                top_k,
                vector_string,
                document_id,
            )

        # ---------------------------------------
        # Search across all documents
        # ---------------------------------------

        else:

            sql = """
                SELECT TOP ?
                    ID,
                    DOCUMENT_ID,
                    CHUNK_INDEX,
                    CHUNK_TEXT,
                    COSINE_SIMILARITY(
                        EMBEDDING,
                        TO_REAL_VECTOR(?)
                    ) AS SCORE
                FROM RAG_DOCUMENT_CHUNKS
                ORDER BY SCORE DESC
            """

            parameters = (
                top_k,
                vector_string,
            )

        try:

            cursor.execute(
                sql,
                parameters
            )

            rows = cursor.fetchall()

        finally:
            cursor.close()

        results = []

        for row in rows:

            results.append(
                {
                    "id": row[0],
                    "document_id": row[1],
                    "chunk_index": row[2],
                    "chunk_text": row[3],
                    "score": float(row[4]),
                }
            )

        return results

    # ==================================================
    # DELETE DOCUMENT
    # ==================================================

    def delete_document(
        self,
        document_id: str,
    ) -> None:

        """
        Delete all chunks belonging to a document.

        Used when the same document is uploaded again.
        """

        if not document_id or not document_id.strip():
            raise ValueError(
                "Document ID cannot be empty."
            )

        connection = self._get_connection()
        cursor = connection.cursor()

        sql = """
            DELETE FROM RAG_DOCUMENT_CHUNKS
            WHERE DOCUMENT_ID = ?
        """

        try:

            cursor.execute(
                sql,
                (document_id,)
            )

            connection.commit()

        finally:
            cursor.close()

    # ==================================================
    # DOCUMENT EXISTS
    # ==================================================

    def document_exists(
        self,
        document_id: str,
    ) -> bool:

        if not document_id or not document_id.strip():
            return False

        connection = self._get_connection()
        cursor = connection.cursor()

        sql = """
            SELECT COUNT(*)
            FROM RAG_DOCUMENT_CHUNKS
            WHERE DOCUMENT_ID = ?
        """

        try:

            cursor.execute(
                sql,
                (document_id,)
            )

            row = cursor.fetchone()

        finally:
            cursor.close()

        return bool(
            row and row[0] > 0
        )

    # ==================================================
    # CLOSE
    # ==================================================

    def close(self):

        if self.connection:

            self.connection.close()

            self.connection = None